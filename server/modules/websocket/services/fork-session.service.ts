import { sessionsDb } from '@/modules/database/index.js';
import { sessionsService } from '@/modules/providers/index.js';
import type { NormalizedMessage, LLMProvider } from '@/shared/types.js';
import { WebSocketWriter } from '@/modules/websocket/services/websocket-writer.service.js';

const MAX_HISTORY_CHARS = 80_000;
const MAX_TOOL_RESULT_CHARS = 2_000;
const HEAD_TURNS = 5;
const TAIL_TURNS = 15;

function truncateToolResult(content: string | null | undefined): string {
  if (!content) return '';
  if (content.length <= MAX_TOOL_RESULT_CHARS) return content;
  const half = Math.floor(MAX_TOOL_RESULT_CHARS / 2);
  return content.slice(0, half) + `\n…[${content.length - MAX_TOOL_RESULT_CHARS} chars elided]…\n` + content.slice(content.length - half);
}

export function serializeHistory(
  messages: NormalizedMessage[],
  sourceProvider: string,
  sourceSessionId: string,
): string {
  // Filter to meaningful messages only
  const readable = messages.filter((m) => {
    if (!m.kind) return false;
    if (m.kind === 'stream_delta' || m.kind === 'session_created' || m.kind === 'complete' || m.kind === 'status') return false;
    if (m.kind === 'thinking') return false;
    if (!m.role && m.kind !== 'tool_use' && m.kind !== 'tool_result') return false;
    if (m.role === 'user' && !m.content) return false;
    return true;
  });

  // Group into turns: [user, ...assistant/tool]
  type Turn = { user?: NormalizedMessage; parts: NormalizedMessage[] };
  const turns: Turn[] = [];
  let currentTurn: Turn | null = null;
  for (const msg of readable) {
    if (msg.role === 'user' || msg.kind === 'text' && !msg.role) {
      if (msg.role === 'user') {
        currentTurn = { user: msg, parts: [] };
        turns.push(currentTurn);
      } else if (currentTurn) {
        currentTurn.parts.push(msg);
      }
    } else {
      if (!currentTurn) {
        currentTurn = { parts: [] };
        turns.push(currentTurn);
      }
      currentTurn.parts.push(msg);
    }
  }

  // Apply head+tail truncation if too many turns
  let selectedTurns = turns;
  if (turns.length > HEAD_TURNS + TAIL_TURNS) {
    const head = turns.slice(0, HEAD_TURNS);
    const tail = turns.slice(turns.length - TAIL_TURNS);
    const elided = turns.length - HEAD_TURNS - TAIL_TURNS;
    selectedTurns = [
      ...head,
      { parts: [{ kind: 'text', content: `[... ${elided} earlier turns elided ...]`, id: 'elide', sessionId: '', timestamp: '', provider: sourceProvider as LLMProvider }] } as Turn,
      ...tail,
    ];
  }

  // Serialize each turn
  const lines: string[] = [
    `[Forked conversation history — replayed from ${sourceProvider} session ${sourceSessionId}]`,
    `The following is a prior conversation. Continue it as if it were your own context.`,
    '',
  ];

  for (const turn of selectedTurns) {
    if (turn.user) {
      lines.push(`## User`);
      lines.push(turn.user.content || '');
      lines.push('');
    }
    for (const part of turn.parts) {
      if (part.kind === 'tool_use') {
        lines.push(`## Tool Use (${part.toolName || 'tool'})`);
        if (part.toolInput) lines.push(JSON.stringify(part.toolInput).slice(0, 500));
        lines.push('');
      } else if (part.kind === 'tool_result') {
        const resultContent = truncateToolResult(part.toolResult?.content);
        lines.push(`### Tool Result`);
        if (resultContent) lines.push(resultContent);
        lines.push('');
      } else if (part.role === 'assistant' || part.kind === 'text' || part.kind === 'stream_end') {
        const content = part.content || part.text || '';
        if (content) {
          lines.push(`## Assistant`);
          lines.push(content);
          lines.push('');
        }
      }
    }
  }

  lines.push('[End of replayed history. Now continue with the following user message:]');
  lines.push('');

  let result = lines.join('\n');

  // Hard cap on total length
  if (result.length > MAX_HISTORY_CHARS) {
    const truncated = result.slice(result.length - MAX_HISTORY_CHARS);
    result = `[History was truncated to fit context window. Showing last ~${MAX_HISTORY_CHARS} chars]\n\n` + truncated;
  }

  return result;
}

/**
 * ForkWriter wraps a WebSocketWriter and intercepts setSessionId to capture
 * the new session id generated by the target provider, then writes lineage.
 */
export class ForkWriter extends WebSocketWriter {
  private _onNewSessionId: (newId: string) => void;
  private _notified = false;

  constructor(
    base: WebSocketWriter,
    onNewSessionId: (newId: string) => void,
  ) {
    super(base.ws, base.userId);
    this.sessionId = base.sessionId;
    this._onNewSessionId = onNewSessionId;
  }

  override setSessionId(sessionId: string): void {
    super.setSessionId(sessionId);
    if (!this._notified) {
      this._notified = true;
      try {
        this._onNewSessionId(sessionId);
      } catch (err) {
        console.error('[Fork] Failed to write lineage:', err);
      }
    }
  }
}

/**
 * Builds a ForkWriter that persists the new session + its lineage as soon as the
 * target provider announces its freshly generated session id.
 *
 * The DB row for a new session is normally created lazily by the periodic
 * session synchronizer (it scans each provider's on-disk store). That has not
 * run yet at the moment the target tool emits its first session id, so a bare
 * `markForked` UPDATE would match zero rows and the lineage would be lost.
 * We therefore upsert the row first (idempotent — a later synchronizer pass
 * re-upserts it without ever touching the lineage columns), then stamp lineage.
 */
export function createForkWriter(
  writer: WebSocketWriter,
  sourceSessionId: string,
  sourceProvider: string,
  targetProvider: string,
  projectPath: string,
): ForkWriter {
  return new ForkWriter(writer, (newId) => {
    console.log(
      `[Fork] New ${targetProvider} session ${newId} forked from ${sourceProvider}/${sourceSessionId}`,
    );
    try {
      sessionsDb.createSession(newId, targetProvider, projectPath || '');
    } catch (err) {
      console.error('[Fork] Failed to create forked session row:', err);
    }
    sessionsDb.markForked(newId, sourceSessionId, sourceProvider);
  });
}

/**
 * Fetches and serializes history from sourceSessionId, returns the full history prompt.
 * Returns null if source session not found or history is empty.
 */
export async function buildForkHistoryPrompt(
  sourceSessionId: string,
  sourceProvider: string,
): Promise<string | null> {
  try {
    const result = await sessionsService.fetchHistory(sourceSessionId, { limit: null });
    if (!result || !Array.isArray(result.messages) || result.messages.length === 0) {
      return null;
    }
    return serializeHistory(result.messages, sourceProvider, sourceSessionId);
  } catch (err) {
    console.error(`[Fork] Failed to fetch history for ${sourceSessionId}:`, err);
    return null;
  }
}
